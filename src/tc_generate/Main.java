    private void btnCheckActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckActionPerformed
        // TODO add your handling code here:
        Check check = new Check();
        
        char[] _tc = txt.getText().toCharArray();
        int[] tc = new int[_tc.length];
        
        for(int i = 0; i < _tc.length; i++){
            tc[i] = Character.getNumericValue(_tc[i]);
        }
        
        check.setTC(tc);
        
        if(check.getCheck()){
            JOptionPane.showMessageDialog(null, "TC gerçek");
        } else {
            JOptionPane.showMessageDialog(null, "TC sahte");
        }
    }//GEN-LAST:event_btnCheckActionPerformed

